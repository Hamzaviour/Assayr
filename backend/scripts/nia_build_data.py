def main() -> None:
    ids = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    refs = list(ids["pdf_refs"])
    for ref in ids.get("workbook_only", []):
        if ref not in refs:
            refs.append(ref)
    codes = [d[0] for d in DOMAINS]
    refs.sort(key=lambda r: (codes.index(r.split()[0]), int(r.split()[1])))
    missing = [r for r in refs if r not in M]
    unknown = [r for r in M if r not in refs]
    if missing or unknown:
        raise SystemExit(f"mapping missing {missing}, unknown {unknown}")
    starred = set(ids.get("starred", []))
    data = {
        "source": "NCSA National Information Assurance Standard V2.1 (May 2023): IDs only, no NCSA text",
        "domains": [{"code": c, "name": n, "summary": s, "order": i} for i, (c, n, s) in enumerate(DOMAINS)],
        "controls": [
            {"ref": r, "domain": r.split()[0], "order": i, "mandatory": r in starred}
            for i, r in enumerate(refs)
        ],
        "mapping": [
            {
                "ref": r,
                "iso": [c for c in M[r][0].split(",") if c],
                "coverage": "full" if M[r][1] == "f" else "partial",
            }
            for r in refs
        ],
    }
    out = Path(__file__).parents[1] / "src/assayr/catalogue/data/nia_v2_1.json"
    out.write_text(json.dumps(data, indent=1) + "\n", encoding="utf-8")
